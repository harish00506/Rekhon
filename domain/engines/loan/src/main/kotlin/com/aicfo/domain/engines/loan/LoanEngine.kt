 * Result: a [LoanEngine]. Input: none. Output: the engine.
 * Changelog: 2026-08-19 — Created for issue 6.2.
 */
object LoanEngineFactory {
    /** Result: the production engine. Input: none. Output: [LoanEngine]. */
    fun create(): LoanEngine = DefaultLoanEngine()
}
